-- Run once in Supabase SQL Editor. No public uploads, submissions or user registration.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  added_at timestamptz not null default now()
);
create table if not exists public.content_items (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('event','problem','archive','resource','member')),
  title text not null check (length(title) between 1 and 250),
  summary text not null default '',
  body text not null default '',
  event_date text not null default '',
  location text not null default '',
  external_url text not null default '',
  image_url text not null default '',
  author text not null default '',
  year_label text not null default '',
  role text not null default '',
  sort_order integer not null default 0,
  featured boolean not null default false,
  published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.site_settings (
  key text primary key,
  value text not null default ''
);
create or replace function public.is_pioneers_admin()
returns boolean language sql stable security definer
set search_path = ''
as $$select exists(select 1 from public.admin_users where user_id= (select auth.uid()))$$;
revoke all on function public.is_pioneers_admin() from public;
grant execute on function public.is_pioneers_admin() to anon, authenticated;
alter table public.admin_users enable row level security;
alter table public.content_items enable row level security;
alter table public.site_settings enable row level security;
-- Require admin membership; simply knowing the publishable API key cannot grant write access.
create policy "admins can see own role" on public.admin_users for select to authenticated using (user_id=(select auth.uid()));
create policy "public can read published content" on public.content_items for select to anon, authenticated using (published=true or public.is_pioneers_admin());
create policy "only admin inserts" on public.content_items for insert to authenticated with check (public.is_pioneers_admin());
create policy "only admin updates" on public.content_items for update to authenticated using (public.is_pioneers_admin()) with check (public.is_pioneers_admin());
create policy "only admin deletes" on public.content_items for delete to authenticated using (public.is_pioneers_admin());
create policy "settings are public" on public.site_settings for select to anon, authenticated using (true);
create policy "admin can add settings" on public.site_settings for insert to authenticated with check (public.is_pioneers_admin());
create policy "admin can change settings" on public.site_settings for update to authenticated using (public.is_pioneers_admin()) with check (public.is_pioneers_admin());
